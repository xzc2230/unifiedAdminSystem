-- JEECG package module dev addition. No source account, menu or Quartz DDL.
SET NAMES utf8mb4;

-- Isolated pack statistics module. Rollback = drop 4 tables + menus/job below.

CREATE TABLE IF NOT EXISTS pkg_pack_stat (
  id                 BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
  tenant_id          INT NOT NULL COMMENT 'JEECG tenant',
  owner_user_id      VARCHAR(64) NOT NULL COMMENT 'JEECG user',
  platform           VARCHAR(16)  NOT NULL COMMENT 'android/ios',
  store_url          VARCHAR(512) NOT NULL COMMENT '商店链接',
  region_code        VARCHAR(8)   NULL DEFAULT NULL COMMENT '上架地区 ISO alpha-2',
  customer_category  VARCHAR(16)  NOT NULL DEFAULT '公司' COMMENT '分类：CT/公司',
  customer           VARCHAR(128) NULL DEFAULT NULL COMMENT '客户',
  is_replenish       TINYINT(1)   NOT NULL DEFAULT 0 COMMENT '是否补包 0否 1是',
  replenish_url      VARCHAR(512) NULL DEFAULT NULL COMMENT '补包链接',
  packer             VARCHAR(64)  NULL DEFAULT NULL COMMENT '出包人',
  notify_email       VARCHAR(512) NULL DEFAULT NULL COMMENT '通知邮箱，多个逗号分隔',
  pass_date          DATE         NULL DEFAULT NULL COMMENT '过包时间',
  customer_use_date  DATE         NULL DEFAULT NULL COMMENT '客户使用时间',
  drop_date          DATE         NULL DEFAULT NULL COMMENT '掉包时间',
  survive_days       INT          NULL DEFAULT NULL COMMENT '存活天数（检测回写）',
  use_days           INT          NULL DEFAULT NULL COMMENT '使用天数（检测回写）',
  designer           VARCHAR(64)  NULL DEFAULT NULL COMMENT '美工',
  remark             VARCHAR(512) NULL DEFAULT NULL COMMENT '备注',
  create_by          VARCHAR(64)  NULL DEFAULT '',
  create_time        DATETIME     NULL DEFAULT NULL,
  update_by          VARCHAR(64)  NULL DEFAULT '',
  update_time        DATETIME     NULL DEFAULT NULL,
  PRIMARY KEY (id),
  KEY idx_pkg_pack_stat_tenant_owner (tenant_id, owner_user_id),
  KEY idx_pkg_pack_stat_packer_pass (packer, pass_date),
  KEY idx_pkg_pack_stat_drop_date (drop_date),
  KEY idx_pkg_pack_stat_region (region_code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='包统计主表（隔离模块）';

CREATE TABLE IF NOT EXISTS pkg_pack_stat_region (
  id          BIGINT      NOT NULL AUTO_INCREMENT COMMENT '主键',
  code        VARCHAR(8)  NOT NULL COMMENT 'ISO alpha-2 小写',
  name_cn     VARCHAR(64) NOT NULL COMMENT '中文名',
  enabled     TINYINT(1)  NOT NULL DEFAULT 1 COMMENT '是否启用',
  sort_order  INT         NOT NULL DEFAULT 0 COMMENT '排序',
  PRIMARY KEY (id),
  UNIQUE KEY uk_pkg_pack_stat_region_code (code)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='包统计上架地区';

CREATE TABLE IF NOT EXISTS pkg_pack_stat_detect_config (
  id                           BIGINT NOT NULL AUTO_INCREMENT COMMENT '主键',
  api_interval_seconds         INT    NOT NULL DEFAULT 2 COMMENT '请求间隔秒',
  thread_count                 INT    NOT NULL DEFAULT 1 COMMENT '探测线程数',
  detection_frequency_minutes  INT    NOT NULL DEFAULT 10 COMMENT '探测频率分钟（与 Quartz cron 对齐）',
  notify_email                 VARCHAR(512) NULL DEFAULT NULL COMMENT '全局通知邮箱，多个逗号分隔',
  updated_at                   DATETIME NULL DEFAULT NULL,
  PRIMARY KEY (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='包统计探测配置（单行）';

CREATE TABLE IF NOT EXISTS pkg_pack_stat_detect_history (
  id             BIGINT       NOT NULL AUTO_INCREMENT COMMENT '主键',
  stat_id        BIGINT       NOT NULL COMMENT 'pkg_pack_stat.id',
  store_url      VARCHAR(512) NOT NULL COMMENT '商店链接',
  region         VARCHAR(8)   NULL DEFAULT NULL COMMENT '地区',
  detect_result  VARCHAR(16)  NOT NULL COMMENT 'NORMAL/DELISTED/INVALID',
  message        VARCHAR(512) NULL DEFAULT NULL COMMENT '探测说明',
  checked_at     DATETIME     NOT NULL COMMENT '探测时间',
  PRIMARY KEY (id),
  KEY idx_pkg_pack_stat_detect_history_stat (stat_id, checked_at),
  KEY idx_pkg_pack_stat_detect_history_checked (checked_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='包统计探测历史';

INSERT INTO pkg_pack_stat_detect_config (api_interval_seconds, thread_count, detection_frequency_minutes, notify_email, updated_at)
SELECT 2, 1, 10, NULL, NOW()
FROM DUAL
WHERE NOT EXISTS (SELECT 1 FROM pkg_pack_stat_detect_config LIMIT 1);

